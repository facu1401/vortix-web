(function () {
  const track = document.getElementById('sliderTrack');
  const dotsEl = document.getElementById('slDots');
  if (!track || !dotsEl) return;

  const slides = track.querySelectorAll('.slide');
  let current = 0;
  let timer;

  slides.forEach((_, i) => {
    const dot = document.createElement('button');
    dot.className = 'sl-dot' + (i === 0 ? ' on' : '');
    dot.setAttribute('aria-label', 'Slide ' + (i + 1));
    dot.onclick = () => { goTo(i); resetTimer(); };
    dotsEl.appendChild(dot);
  });

  function goTo(idx) {
    current = (idx + slides.length) % slides.length;
    track.style.transform = `translateX(-${current * 100}%)`;
    dotsEl.querySelectorAll('.sl-dot').forEach((d, i) => d.classList.toggle('on', i === current));
  }

  window.sliderMove = function (dir) {
    goTo(current + dir);
    resetTimer();
  };

  function resetTimer() {
    clearInterval(timer);
    timer = setInterval(() => goTo(current + 1), 5000);
  }

  resetTimer();
})();

