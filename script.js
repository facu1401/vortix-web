function openModal(e, idx){
  e.stopPropagation();
  const p = prods[idx];
  const d = prodDetails[idx] || prodDetails[0];
  curProd = {p, d, idx};
  carIdx = 0;
  carTotal = d.slides.length;

  // badge
  const mb = document.getElementById('m-badge');
  if(p.b){
    const bmap={n:'bn',h:'bh',s:'bs'};
    const btxt={n:{es:'NUEVO',en:'NEW',pt:'NOVO'},h:{es:'🔥 HOT',en:'🔥 HOT',pt:'🔥 QUENTE'},s:{es:'🏷 OFERTA',en:'🏷 SALE',pt:'🏷 OFERTA'}};
    const bk=p.b[0];
    mb.innerHTML=`<div class="modal-badge ${bmap[bk]||'bn'}">${btxt[bk]?.[lang]||p.b.toUpperCase()}</div>`;
  } else { mb.innerHTML=''; }

  // cat / name / stars
  document.getElementById('m-cat').textContent = '⬡ ' + (catN[p.cat]?.[lang]||p.cat);
  document.getElementById('m-name').textContent = p.n;
  document.getElementById('m-stars').textContent = '★'.repeat(p.r)+'☆'.repeat(5-p.r);
  document.getElementById('m-reviews').textContent = `(${p.rv} reseñas)`;

  // desc
  document.getElementById('m-desc').textContent = d.desc;

  // price
  document.getElementById('m-old').textContent = p.op ? `$${p.op}` : '';
  document.getElementById('m-price').textContent = `$${p.p}`;

  // tags
  document.getElementById('m-tags').innerHTML = d.tags.map(t=>`<span class="modal-tag">#${t}</span>`).join('');

  // tape
  document.getElementById('modal-tape').textContent = '⚡ ' + (catN[p.cat]?.[lang]||p.cat).toUpperCase();

  // carousel
  buildCarousel(d);

  // fav reset
  modalFavOn = false;
  document.getElementById('m-fav-btn').textContent = '🤍 Favorito';

  // open
  document.getElementById('modal-overlay').classList.add('open');
  document.body.style.overflow = 'hidden';
}

function buildCarousel(d){
  const track = document.getElementById('car-track');
  const dots = document.getElementById('car-dots');
  track.innerHTML = '';
  dots.innerHTML = '';
  d.slides.forEach((emoji, i) => {
    const slide = document.createElement('div');
    slide.className = 'carousel-slide';
    slide.setAttribute('data-label', d.labels[i]||'');
    slide.innerHTML = `<span class="carousel-emoji">${emoji}</span>`;
    track.appendChild(slide);
    const dot = document.createElement('div');
    dot.className = 'car-dot' + (i===0?' on':'');
    dot.onclick = ()=>carGo(i);
    dots.appendChild(dot);
  });
  track.style.transform = 'translateX(0)';
}

function carMove(dir){
  carIdx = (carIdx + dir + carTotal) % carTotal;
  carGo(carIdx);
}
function carGo(i){
  carIdx = i;
  document.getElementById('car-track').style.transform = `translateX(-${i*100}%)`;
  document.querySelectorAll('.car-dot').forEach((d,j)=>d.classList.toggle('on',j===i));
}

function closeModal(){
  document.getElementById('modal-overlay').classList.remove('open');
  document.body.style.overflow = '';
}
function closeModalOutside(e){
  if(e.target === document.getElementById('modal-overlay')) closeModal();
}

