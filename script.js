let curFilter = 'all';

function renderProds(f) {
  if (f !== undefined) curFilter = f;
  const grid = document.getElementById('pgrid');
  const list = curFilter === 'all' ? prods : prods.filter(p => p.cat === curFilter);
  grid.innerHTML = '';
  list.forEach((p, i) => {
    const prodIdx = prods.indexOf(p);
    const st = '★'.repeat(p.r) + '☆'.repeat(5 - p.r);
    const badge = p.b ? `<div class="pbadge b${p.b[0]}">${badgeN[p.b]?.[lang] || p.b.toUpperCase()}</div>` : '';
    const cn = catN[p.cat]?.[lang] || p.cat;
    const name = typeof p.n === 'object' ? p.n[lang] || p.n.es : p.n;
    const desc = typeof p.desc === 'object' ? p.desc[lang] || p.desc.es : p.desc;
    const imgHtml = p.img
      ? `<img class="pimg-real" src="${p.img}" alt="${name}" onerror="this.style.display='none'"/>`
      : '';
    const d = document.createElement('div');
    d.className = 'pc rev';
    d.style.transitionDelay = `${i * 0.05}s`;
    d.innerHTML = `
      ${badge}
      <div class="pfav" onclick="doFav(this,event)">&#9825;</div>
      <div class="pci ${p.cc}">
        <div class="pimg">${imgHtml}</div>
        <div class="pbody">
          <div class="pcat">${cn}</div>
          <div class="pname">${name}</div>
          <div style="display:flex;align-items:center;gap:4px;margin-bottom:7px;">
            <span class="pstars">${st}</span>
            <span class="prev">(${p.rv})</span>
          </div>
          <div class="pfooter">
            <div class="pprice-w">
              <span class="pprice">${fmtPrice(p.p)}</span>
            </div>
            <button class="pbtn" onclick="openModal(event,${prodIdx})">${T[lang].btn_v || 'Ver más'}</button>
          </div>
        </div>
      </div>`;
    grid.appendChild(d);
    requestAnimationFrame(() => requestAnimationFrame(() => d.classList.add('vis')));
  });
}

function fcat(el, cat) {
  document.querySelectorAll('#cfilt .fi').forEach(i => i.classList.remove('on'));
  el.classList.add('on');
  renderProds(cat);
}

function doFav(btn, e) {
  e.stopPropagation();
  const on = btn.innerHTML.includes('9829'); // ♥
  btn.innerHTML = on ? '&#9825;' : '&#9829;';
  btn.style.transform = on ? '' : 'scale(1.4) rotate(-10deg)';
  setTimeout(() => btn.style.transform = '', 300);
  showToast(on ? T[lang].toast_fav_rm : T[lang].toast_fav_add);
}

let ttimer;
function showToast(msg) {
  const t = document.getElementById('toast');
  document.getElementById('tm').textContent = msg;
  t.classList.add('show');
  clearTimeout(ttimer);
  ttimer = setTimeout(() => t.classList.remove('show'), 2400);
}

