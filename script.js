function sendContact(btn){
  const name  = document.getElementById('cf-name').value.trim();
  const email = document.getElementById('cf-email').value.trim();
  const msg   = document.getElementById('cf-msg').value.trim();
  if(!name||!email||!msg){ showToast('⚠️ Rellena todos los campos','⚠️'); return; }
  btn.textContent='✓ Enviado!';
  btn.classList.add('sent');
  btn.disabled=true;
  document.getElementById('cform-ok').classList.add('show');
  showToast('¡Mensaje enviado! 📬','📬');
  setTimeout(()=>{
    btn.textContent='🚀 Enviar mensaje';
    btn.classList.remove('sent');
    btn.disabled=false;
    document.getElementById('cform-ok').classList.remove('show');
    ['cf-name','cf-email','cf-msg'].forEach(id=>document.getElementById(id).value='');
  }, 4000);
}

